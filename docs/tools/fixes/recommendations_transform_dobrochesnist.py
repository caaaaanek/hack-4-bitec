"""Document-specific fixes for recommendations_transform_dobrochesnist.pdf (cover, TOC, headings, Анкета 1/2).

Usage: python3 -I tools/fixes/recommendations_transform_dobrochesnist.py md/recommendations_transform_dobrochesnist.md
Run BEFORE tools/fixes/common.py.
"""
import sys, re
p = sys.argv[1]; t = open(p, encoding='utf-8').read()

head, rest = t.split('## ВСТУП', 1)
cover = """# Рекомендації щодо трансформації функціонування вищих військових навчальних закладів (військових навчальних підрозділів закладів вищої освіти) на засадах доброчесності та нульової толерантності до корупції

**Міністерство оборони України**
Департамент з питань запобігання та виявлення корупції Міністерства оборони України
Національний університет оборони України

Київ – 2025

## ЗМІСТ

- Вступ — 3
- 1. Трансформація системи антикорупційної роботи у ВВНЗ (ВНП ЗВО) в послідовну та взаємопов’язану політику розбудови доброчесності за стандартами НАТО — 4
  - 1.1. Нормативне підґрунтя розвитку культури доброчесності та нульової толерантності до корупції у ВВНЗ (ВНП ЗВО) — 4
  - 1.2. Завдання трансформації функціонування ВВНЗ (ВНП ЗВО) на засадах прозорості та доброчесності — 6
- 2. Алгоритм трансформації функціонування ВВНЗ (ВНП ЗВО) на засадах доброчесності та нульової толерантності до корупції та його практичне застосування — 9
- Закінчення — 17
- Перелік посилань — 18
- Додатки — 20

"""
t = cover + '## ВСТУП' + rest

def sub1(old, new):
    global t
    assert t.count(old) >= 1, old[:60]
    t = t.replace(old, new, 1)

sub1('**2. Алгоритм трансформації функціонування ВВНЗ (ВНП ЗВО) на засадах доброчесності та нульової толерантності до корупції та його практичне застосування**',
     '## 2. Алгоритм трансформації функціонування ВВНЗ (ВНП ЗВО) на засадах доброчесності та нульової толерантності до корупції та його практичне застосування')
t = re.sub(r'(визначенням умов, що призвели до такої ситуації\.) \*\*(3\.4\. Аудит \(моніторинг\) ефективності системи доброчесності:)\*\*',
           r'\1\n\n### \2', t)
t = re.sub(r'(?m)^\\\*\\\*\n\n', '', t)
# appendices: lower the level of block titles inside them
t = re.sub(r'(?m)^## (Міністерство оборони України|м\. Київ|НАКАЗУЮ:)$', r'**\1**', t)
t = re.sub(r'(?m)^## (НАКАЗ .*)$', r'### \1', t)
t = re.sub(r'(?m)^## (ЗВІТ .*)$', r'### \1', t)
t = re.sub(r'(?m)^## (ВАЖЛИВО:)$', r'**\1**', t)
# questionnaires in appendix B
n = [0]
def anketa(m):
    n[0] += 1
    return f'### Анкета {n[0]}\n\n' + m.group(0)
t = re.sub(r'(?m)^Анкета\\\* опитування .*$', anketa, t)
# glued multi-line sub-titles "Додаток 1 / до ..."
t = re.sub(r'(?m)^(Додаток [12])\n\n(до [^\n]+)\n\n([^\n|#]+)\n\n([^\n|#]+)\n\n', r'**\1**\n\2 \3 \4\n\n', t)
t = re.sub(r'(?m)^(Додаток 1)\n\n(до наказу начальника)\n\n', r'**\1**\n\2 ', t)
open(p, 'w', encoding='utf-8').write(t)
